-- ============================================================
-- Fix 37: Daily dispatch (Ачилт), bank-transfer payments, e-Barimt queue
-- ============================================================
-- Brings Mercury's daily screens into the website:
--
--   Mercury                          Website
--   ───────────────────────────────  ─────────────────────────────────────
--   Захиалгын хүргэлт хуваарлах      /admin/dispatch   (shipments + orders.shipment_id)
--   Хаасан захиалгын жагсаалт        /admin/shipments  (shipments.status = 'closed')
--   Падаан / Нэгтгэл хэвлэх          /print/invoices, /print/picklist
--   НӨАТУС V3 (e-Barimt)             /admin/ebarimt    (ebarimt_receipts)
--
-- e-Barimt receipts are queued here by the website and sent by the
-- e-Barimt agent (web/scripts/ebarimt-agent.mjs), which runs on the BDI
-- computer next to PosAPI 3.0 — PosAPI is a local service and can't be
-- reached from Vercel. The agent uses the service role; admins read and
-- queue through RLS below.
--
-- Nothing here changes existing rows. Idempotent — safe to re-run.
-- ============================================================


-- 1. Bank transfer ("Дансаар") next to cash and credit -------------------
alter type public.payment_method add value if not exists 'transfer';


-- 2. Distributors (Түгээгч) — who takes a shipment out ------------------
-- Most delivery people have no website account, so this is a plain list.
create table if not exists public.distributors (
  id         uuid primary key default gen_random_uuid(),
  name       text not null,
  phone      text,
  vehicle    text,
  active     boolean not null default true,
  created_at timestamptz not null default now()
);
create unique index if not exists distributors_name_key
  on public.distributors (lower(name));

-- Mercury's only distributor today ("5001 : Мөнхөө 88689949").
insert into public.distributors (name, phone)
select 'Мөнхөө', '88689949'
where not exists (
  select 1 from public.distributors where lower(name) = lower('Мөнхөө')
);


-- 3. Shipments (Ачилт) --------------------------------------------------
-- A delivery run: the orders one distributor takes out on one day.
-- 'open' while orders are being assigned; 'closed' when loaded and sent
-- out (its orders become 'shipped').
create table if not exists public.shipments (
  id             uuid primary key default gen_random_uuid(),
  shipment_no    bigint generated by default as identity unique,
  delivery_date  date not null,
  distributor_id uuid references public.distributors(id) on delete set null,
  status         text not null default 'open'
                 check (status in ('open', 'closed')),
  notes          text,
  created_by     uuid references public.profiles(id) on delete set null,
  created_at     timestamptz not null default now(),
  closed_at      timestamptz,
  closed_by      uuid references public.profiles(id) on delete set null
);
create index if not exists shipments_delivery_date_idx
  on public.shipments (delivery_date desc);

alter table public.orders
  add column if not exists shipment_id uuid
    references public.shipments(id) on delete set null;
-- Planned delivery day (set when an admin enters the order, and to the
-- shipment's day when the order is assigned).
alter table public.orders
  add column if not exists delivery_date date;

create index if not exists orders_shipment_idx on public.orders (shipment_id);
create index if not exists orders_unassigned_idx
  on public.orders (created_at) where shipment_id is null;
create index if not exists orders_shipped_at_idx on public.orders (shipped_at);


-- 4. Store tax id for e-Barimt -----------------------------------------
-- B2B receipts need the buyer's ТТД (TIN), not the registry number (РД).
-- The agent looks it up once from the registry number and keeps it here.
alter table public.supermarkets add column if not exists ebarimt_tin text;
alter table public.supermarkets add column if not exists ebarimt_name text;


-- 5. e-Barimt receipts ---------------------------------------------------
-- One row per send attempt. status flow:
--   queued → sending → sent            (agent: PosAPI said SUCCESS)
--                    → failed          (agent: error; admin can re-queue)
--   sent → return_queued → returning → returned   (Буцаах)
--                                    → sent + error (return refused)
create table if not exists public.ebarimt_receipts (
  id                  uuid primary key default gen_random_uuid(),
  -- PosAPI's billIdSuffix comes from this (6 digits, unique per receipt).
  bill_seq            bigint generated by default as identity unique,
  order_id            uuid not null references public.orders(id) on delete restrict,
  status              text not null default 'queued'
                      check (status in ('queued', 'sending', 'sent', 'failed',
                                        'return_queued', 'returning', 'returned')),
  receipt_type        text not null
                      check (receipt_type in ('B2B_RECEIPT', 'B2C_RECEIPT')),
  registry_number     text,          -- buyer's РД as stored on the store
  customer_tin        text,          -- buyer's ТТД actually sent (B2B)
  total_amount        numeric(14,2) not null,
  total_vat           numeric(14,2) not null default 0,
  total_city_tax      numeric(14,2) not null default 0,
  request             jsonb not null, -- body built by the website (merchant fields added by the agent)
  response            jsonb,          -- PosAPI's answer, verbatim
  bill_id             text,           -- ДДТД
  lottery             text,
  qr_data             text,
  receipt_date        text,           -- PosAPI's "date", sent back verbatim to return the receipt
  error               text,
  attempts            int not null default 0,
  queued_by           uuid references public.profiles(id) on delete set null,
  queued_at           timestamptz not null default now(),
  sent_at             timestamptz,
  return_requested_by uuid references public.profiles(id) on delete set null,
  return_requested_at timestamptz,
  returned_at         timestamptz,
  updated_at          timestamptz not null default now()
);
create index if not exists ebarimt_receipts_order_idx
  on public.ebarimt_receipts (order_id);
create index if not exists ebarimt_receipts_work_idx
  on public.ebarimt_receipts (status, queued_at)
  where status in ('queued', 'sending', 'return_queued', 'returning');
-- One live receipt per order: a new one only after the last failed or was returned.
create unique index if not exists ebarimt_receipts_one_live
  on public.ebarimt_receipts (order_id)
  where status in ('queued', 'sending', 'sent', 'return_queued', 'returning');

drop trigger if exists ebarimt_receipts_updated_at on public.ebarimt_receipts;
create trigger ebarimt_receipts_updated_at
  before update on public.ebarimt_receipts
  for each row execute function public.set_updated_at();


-- 6. Agent heartbeat ------------------------------------------------------
-- The agent writes here every ~30 s so /admin/ebarimt can say whether the
-- e-Barimt computer and PosAPI are up.
create table if not exists public.ebarimt_agent_status (
  id           text primary key default 'main',
  last_seen_at timestamptz,
  posapi_ok    boolean,
  info         jsonb,
  error        text
);


-- 7. RLS: admins only (the agent uses the service role) -----------------
alter table public.distributors         enable row level security;
alter table public.shipments            enable row level security;
alter table public.ebarimt_receipts     enable row level security;
alter table public.ebarimt_agent_status enable row level security;

drop policy if exists distributors_admin_all on public.distributors;
create policy distributors_admin_all on public.distributors
  for all using ((select public.current_role_value()) = 'admin')
  with check ((select public.current_role_value()) = 'admin');

drop policy if exists shipments_admin_all on public.shipments;
create policy shipments_admin_all on public.shipments
  for all using ((select public.current_role_value()) = 'admin')
  with check ((select public.current_role_value()) = 'admin');

drop policy if exists ebarimt_receipts_admin_all on public.ebarimt_receipts;
create policy ebarimt_receipts_admin_all on public.ebarimt_receipts
  for all using ((select public.current_role_value()) = 'admin')
  with check ((select public.current_role_value()) = 'admin');

drop policy if exists ebarimt_agent_status_admin_read on public.ebarimt_agent_status;
create policy ebarimt_agent_status_admin_read on public.ebarimt_agent_status
  for select using ((select public.current_role_value()) = 'admin');


